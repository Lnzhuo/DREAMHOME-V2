import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import {NodeIO} from '@gltf-transform/core';
import {ALL_EXTENSIONS} from '@gltf-transform/extensions';
import {getBounds} from '@gltf-transform/functions';
import {referenceDimensions} from './reference-dimensions.mjs';
import assert from 'node:assert/strict';
const root='data/library';
const index=JSON.parse(await fs.readFile(root+'/index.json')),progress=JSON.parse(await fs.readFile(root+'/new-lux3d-progress.json'));
const a=index.assets.find(a=>a.providerTaskId==='8462069'&&a.name==='软木公告板');
const raw=await fs.readFile('data/projects/v2-generated/assets/'+a.id+'/model.glb');
const sha=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
assert(sha(raw)===a.archive.sha256);
const io=new NodeIO().registerExtensions(ALL_EXTENSIONS),doc=await io.readBinary(raw);
const scene=doc.getRoot().getDefaultScene()||doc.getRoot().listScenes()[0],B=getBounds(scene);
const displayDepth=(B.max[2]-B.min[2])*.72/(B.max[0]-B.min[0]);
const correction=.035/displayDepth;assert(correction>.25 && correction<.65);
const pivot=doc.createNode('board-thickness').setScale([1,1,correction]);
for(const n of scene.listChildren()){scene.removeChild(n);pivot.addChild(n);} scene.addChild(pivot);
const bytes=await io.writeBinary(doc),bounds=getBounds(scene),dims=referenceDimensions(a.name,a.category,bounds);
assert(Math.abs(dims.dimensions.depth.value-.035)<.001 && !dims.exceptions.length);
const dir=root+'/models/'+a.id;await fs.writeFile(dir+'/model.glb',bytes);
a.archive={...a.archive,originalSha256:sha(raw),sha256:sha(bytes),bytes:bytes.length};
a.importCorrection={method:'按展示用设计厚度 0.035 米校正公告板深度',source:'项目设计估算',scaleFactors:[1,1,correction],rawSha256:sha(raw),correctedSha256:sha(bytes)};
a.boundingBox=bounds;a.dimensions=dims.dimensions;a.designReference=dims.reference;a.scaleCalibrationRequired=false;
for(const key of ['thumbnail','thumbnailUrl','planThumbnail','planThumbnailUrl'])delete a[key];
delete progress[a.id];a.qa.visualReview='待人工检查校准后的模型';a.qa.placementTest='待校准后场景复验';
await fs.writeFile(dir+'/asset.json',JSON.stringify(a,null,2));await fs.writeFile(root+'/index.json',JSON.stringify(index,null,2));await fs.writeFile(root+'/new-lux3d-progress.json',JSON.stringify(progress,null,2));
console.log(a.name,a.dimensions.depth);
